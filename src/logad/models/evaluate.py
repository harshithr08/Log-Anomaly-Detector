"""
evaluate.py — grade every detector on the shop dataset.

For each detector:
    1. fit on the train split (clean traffic only, no labels)
    2. threshold from the val split (clean): at most 1 in 1,000 normal flagged
    3. grade on the test split (scheduled faults), using the injector's labels

Writes eval/results/models.md.

Usage:
    python -m logad.models.evaluate
"""

import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from logad.models.baselines import ErrorLine, MarkovChain, UnseenSequence, UnseenTemplate
from logad.models.dataset import DATA_DIR, Splits, load_splits
from logad.models.metrics import FALSE_ALARM_BUDGET, evaluate, threshold_for

RESULTS = Path("eval/results/models.md")


def detectors() -> list:
    return [ErrorLine(), UnseenSequence(), UnseenTemplate(), MarkovChain()]


@dataclass
class Graded:
    row: dict  # the results table row
    threshold: float
    val_scores: np.ndarray
    test_scores: np.ndarray


def grade(detector, splits: Splits) -> Graded:
    """Fit on train, threshold on val, grade on test."""
    started = time.perf_counter()
    detector.fit(splits.train)
    val_scores = detector.score(splits.val)
    threshold = threshold_for(val_scores)
    test_scores = detector.score(splits.test)
    result = evaluate(
        test_scores, [s.label for s in splits.test], [s.fault for s in splits.test], threshold
    )
    row = {"detector": detector.name, **result, "seconds": time.perf_counter() - started}
    return Graded(row, threshold, val_scores, test_scores)


def combine(name: str, graded: list[Graded], splits: Splits) -> dict:
    """Flag a session if ANY of the detectors flags it. For PR-AUC, each score
    becomes its distance above its own threshold, in units of its normal spread."""
    margins = [(g.test_scores - g.threshold) / (np.std(g.val_scores) + 1e-9) for g in graded]
    combined = np.max(margins, axis=0)
    result = evaluate(
        combined, [s.label for s in splits.test], [s.fault for s in splits.test], threshold=0.0
    )
    return {"detector": name, **result}


def _pct(value: float) -> str:
    return "–" if value != value else f"{value:.1%}"  # value != value: NaN


def to_markdown(rows: list[dict], splits: Splits) -> str:
    test_broken = splits.info["test_broken"]
    lines = [
        "# Detectors on the shop dataset",
        "",
        "Generated by `python -m logad.models.evaluate`. Do not edit by hand.",
        "",
        f"Train: {len(splits.train):,} clean sessions. Validation: {len(splits.val):,} clean "
        f"sessions (thresholds: at most {FALSE_ALARM_BUDGET:.1%} of them flagged). "
        f"Test: {len(splits.test):,} sessions during scheduled faults, "
        f"{test_broken:,} of them broken by the fault injector.",
        "",
        "Design choices (features, grouping, which models) were made on a separate "
        "development collection. These numbers come from a fresh collection, "
        "evaluated once.",
        "",
        "| Detector | Precision | Recall | F1 | PR-AUC | False alarms | "
        "Recall: skip | Recall: slow | Recall: error |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['detector']} | {r['precision']:.3f} | {r['recall']:.3f} | **{r['f1']:.3f}** | "
            f"{r['pr_auc']:.3f} | {_pct(r['false_alarm_rate'])} | {_pct(r['recall_skip'])} | "
            f"{_pct(r['recall_slow'])} | {_pct(r['recall_error'])} |"
        )
    lines += [
        "",
        "False alarms = share of the test period's *normal* sessions that were flagged.",
    ]
    return "\n".join(lines) + "\n"


def write_report(rows: list[dict], splits: Splits) -> str:
    report = to_markdown(rows, splits)
    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text(report, encoding="utf-8", newline="\n")
    return report


def main():
    """Baselines only (no PyTorch needed). `python -m logad.models.train`
    grades the baselines and the models together."""
    splits = load_splits(DATA_DIR)
    rows = []
    for detector in detectors():
        print(f"  {detector.name}...", flush=True)
        rows.append(grade(detector, splits).row)
    print(write_report(rows, splits))


if __name__ == "__main__":
    main()
